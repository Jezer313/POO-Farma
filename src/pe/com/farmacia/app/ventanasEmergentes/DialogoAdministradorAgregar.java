    private void btnGuardarAdministradorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarAdministradorActionPerformed
        String nombre = txtNombre.getText().trim();
        String apellido = txtApellido.getText().trim();
        String dni = txtDNI.getText().trim();
        String usuario = txtUsuario.getText().trim();
        String direccion = txtDireccion.getText().trim();
        String contrasena = new String(txtContrasena.getPassword());
        String confirmar = new String(txtConfirmarContrasena.getPassword());

        if (nombre.isEmpty() || apellido.isEmpty() || dni.isEmpty()
                || usuario.isEmpty() || direccion.isEmpty()
                || contrasena.isEmpty() || confirmar.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Completa todos los campos obligatorios.",
                    "Campos incompletos",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        if (!contrasena.equals(confirmar)) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Las contraseñas no coinciden.",
                    "Error de contraseña",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        Administrador admin = new Administrador(0, dni, nombre, apellido, "", direccion);

        if (administradordao.agregar(admin)) {
            Admin credenciales = new Admin(admin.getId_administrador(), usuario, contrasena);
            if (!admindao.registrar(credenciales)) {
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Se guardó el administrador, pero no se pudieron registrar sus credenciales.",
                        "Advertencia",
                        javax.swing.JOptionPane.WARNING_MESSAGE
                );
            }
            guardado = true;
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Administrador guardado correctamente.",
                    "Éxito",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE
            );
            this.dispose();
        } else {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "No se pudo guardar el administrador en la base de datos.",
                    "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btnGuardarAdministradorActionPerformed

