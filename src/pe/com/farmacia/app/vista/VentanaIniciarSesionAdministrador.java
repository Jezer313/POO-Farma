    private void btnRegresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegresarActionPerformed

        // Comprueba que exista una referencia a la ventana de inicio de sesión.
        if (ventanaLogin != null) {

            // Elimina el panel de administrador y recupera la pantalla de inicio.
            ventanaLogin.volverALogin(this);

            // Recupera el tamaño original de la ventana de inicio de sesión.
            ventanaLogin.setSize(600, 320);

            // Centra nuevamente la ventana en la pantalla.
            ventanaLogin.setLocationRelativeTo(null);
        }
    }//GEN-LAST:event_btnRegresarActionPerformed

    private void btnContinuarAdminActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnContinuarAdminActionPerformed
// Obtiene el usuario ingresado y elimina espacios al inicio y al final.
        String usuario = txtUsuarioAdmin.getText().trim();

// Obtiene la contraseña ingresada.
        String contraseña = new String(txtContraseñaAdmin.getPassword());

// Comprueba si el usuario y la contraseña son correctos.
        if (usuario.equals(usuarioAdmin) && contraseña.equals(contraseñaAdmin)) {
            if (ventanaLogin != null) {
                // Quita el PanelAdmin actual de InicioDeSesion
                ventanaLogin.getContentPane().remove(this);

                // Crea VentanaAdministracion como JPanel pasándole ventanaLogin
                VentanaAdministracion panelAdministracion = new VentanaAdministracion(ventanaLogin);

                // Ajusta el tamaño y posición de InicioDeSesion para el panel de administración
                ventanaLogin.setResizable(true);
                ventanaLogin.setSize(1110, 685);
                ventanaLogin.setLocationRelativeTo(null);
                ventanaLogin.setResizable(false);
                ventanaLogin.setTitle("Administracion de farmacia \"El Tilin\"");

                // Agrega el JPanel al contenedor principal de InicioDeSesion
                ventanaLogin.getContentPane().add(panelAdministracion, java.awt.BorderLayout.CENTER);
                ventanaLogin.getContentPane().revalidate();
                ventanaLogin.getContentPane().repaint();
            }
        } else {

            // Descuenta un intento cuando las credenciales son incorrectas.
            intentosRestantes--;

            // Comprueba si todavía quedan intentos disponibles.
            if (intentosRestantes > 0) {

                // Muestra un mensaje con la cantidad de intentos restantes.
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Usuario o contraseña incorrectos.\nIntentos restantes: " + intentosRestantes,
                        "Acceso denegado",
                        javax.swing.JOptionPane.WARNING_MESSAGE
                );

            } else {

                // Muestra el mensaje cuando se agotan los tres intentos.
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Has agotado los 3 intentos. El acceso ha sido bloqueado.",
                        "Acceso bloqueado",
                        javax.swing.JOptionPane.ERROR_MESSAGE
                );

                // Deshabilita los campos de acceso.
                txtUsuarioAdmin.setEnabled(false);
                txtContraseñaAdmin.setEnabled(false);

                // Deshabilita el botón para impedir nuevos intentos.
                btnContinuarAdmin.setEnabled(false);
            }
        }
    }//GEN-LAST:event_btnContinuarAdminActionPerformed


